"""
INVERTIR UNA CADENA DE TEXTO -> REVERSE A TEXT STRING
"""

text_string = "Call of Duty Mobile"

# Inversión de cadena mediante slicing [::-1] -> String reversal using slicing [::-1]
reversed_string = text_string[::-1]

print(f"Cadena original -> Original string: {text_string}")
print(f"Cadena invertida -> Reversed string: {reversed_string}")
