"""
CREAR UNA CADENA DE TEXTO Y MOSTRAR SU LONGITUD -> CREATE A TEXT STRING AND DISPLAY ITS LENGTH
"""

# Entrada de texto por consola -> Console text input
text_input = input("Ingresa una palabra o frase por favor -> Please enter a word or phrase: ")

# Cálculo de la longitud de la cadena con len() -> String length calculation with len()
string_length = len(text_input)

print(f"La longitud de la cadena es -> The length of the string is: {string_length}")
