"""
IMPRIMIR LOS ELEMENTOS DE UNA LISTA DADA -> PRINT THE ELEMENTS OF A GIVEN LIST
"""

numbers_list: list[int] = [10, 20, 30, 40, 50]

print("--- Elementos de la lista -> List elements ---")

# Iteración directa sobre cada elemento de la lista -> Direct iteration over each element in the list
