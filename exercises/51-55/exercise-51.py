"""
IMPRIMIR LOS NÚMEROS DEL 1 AL 5 CON EL CICLO FOR -> PRINT NUMBERS FROM 1 TO 5 USING A FOR LOOP
"""

print("--- Números del 1 al 5 -> Numbers from 1 to 5 ---")

# range(1, 6) genera números desde 1 hasta 5 (el 6 es exclusivo) -> range(1, 6) generates numbers from 1 to 5 (6 is exclusive)
for number in range(1, 6):
    print(number)
