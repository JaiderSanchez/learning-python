"""
IMPRIMIR LOS NÚMEROS DEL 10 AL 1 EN ORDEN DESCENDENTE -> PRINT NUMBERS FROM 10 DOWN TO 1 IN DESCENDING ORDER
"""

# Inicialización del contador -> Counter initialization
counter = 10

print("--- Conteo Regresivo -> Countdown ---")

# Bucle while para iteración decreciente -> While loop for decreasing iteration
while counter >= 1:
    print(counter)
    counter -= 1
