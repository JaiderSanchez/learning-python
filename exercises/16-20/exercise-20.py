"""
CONTAR LAS OCURRENCIAS DE UN CARÁCTER ESPECÍFICO EN UNA CADENA -> COUNT THE OCCURRENCES OF A SPECIFIC CHARACTER IN A STRING
"""

text_string = "Programming solves problems."

# Conteo de frecuencia con .count() -> Frequency count using .count()
occurrences_count = text_string.count("m")

print(f"Número de ocurrencias de la letra 'm' -> Number of occurrences of the letter 'm': {occurrences_count}")


# IMPORTANT NOTE: "En programación y bases de datos, una ocurrencia es el número de veces que aparece un elemento, valor, carácter o registro específico dentro de un conjunto de datos, o bien un ejemplar concreto (una instancia) de una entidad" -> "In programming and databases, an occurrence refers to the number of times a specific element, value, character, or record appears within a dataset, or alternatively, a specific example (an instance) of an entity."

# En este caso, se utilizó la 'ocurrencia' para el 'Conteo de apariciones (Frecuencia)'. Se refiere a cuántas veces se repite un dato dentro de una estructura (como un array, una lista, una cadena de texto o una base de datos). -> In this case, 'occurrence' was used to refer to a 'count of appearances (frequency)'. It indicates how many times a piece of data is repeated within a structure (such as an array, a list, a text string, or a database).
