"""
CALCULAR 2 ELEVADO A LA 4ta POTENCIA SIN USAR EL OPERADOR ** -> CALCULATE 2 TO THE 4TH POWER WITHOUT USING THE ** OPERATOR
"""

# Definición de base y exponente -> Base and exponent definition
base_number = 2
exponent_number = 4

# La función pow(base, exp) calcula la potencia -> The pow(base, exp) function calculates the power
power_result = pow(base_number, exponent_number)

print(f"El resultado de {base_number} elevado a la potencia {exponent_number} es -> The result of {base_number} raised to power {exponent_number} is: {power_result}")
