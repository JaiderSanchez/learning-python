# math_box/suma_resta.py
# Herramientas básicas de suma y resta -> Basic addition and subtraction tools

def sumar(a: int, b: int) -> int:
    """Suma dos números enteros -> Adds two numbers."""
    return a + b

def restar(a: int, b: int) -> int:
    """Resta dos números -> Subtracts two numbers."""
    return a - b

